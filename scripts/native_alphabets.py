def skeleton(char):
    item=GREEK.get(char,LATIN.get(char))
    if isinstance(item,str): item=LATIN[item]
    if item is None: raise KeyError('No original skeleton for '+char)
    return item


def draw_skeleton(width,data,thickness):
    p=pathops.Path();parse_path(data,p.getPen())
    p.stroke(thickness,pathops.LineCap.BUTT_CAP,pathops.LineJoin.ROUND_JOIN,4)
    p.convertConicsToQuads(0.03)
    return from_path(pathops.simplify(p),width)


def sans(char,bold=False,italic=False,mono=False):
    w,data=skeleton(char);g=draw_skeleton(w,data,106 if bold else 65)
    if mono:
        x0,y0,x1,y1=bounds(g);sx=min(1,530/(x1-x0))
        g=transform(g,xx=sx,dx=325-(x0+x1)*sx/2,width=650)
        # Distinguish I/l/1, with understated fixed-width terminal bars.
        if char=='I':
            top=710
            g=combine(g,rect(170,0,480,43),rect(170,top-43,480,top),width=650)
        elif char=='l':
            g=draw_skeleton(650,'M195 745 H325 V120 C325 25 405 0 500 0',65)
    if italic:g=transform(g,yx=0.19,width=g['width'])
    return clean(g)


def fraktur(char,bold=False):
    thick=112 if bold else 83
    if char in FRAKTUR:
        w,data=FRAKTUR[char]
        # A narrow pen gives broad verticals and fine oblique joins.
        p=pathops.Path();parse_path(data,p.getPen())
        rec=RecordingPen();p.draw(rec)
        stretched=[]
        for op,pts in rec.value:stretched.append((op,[(x,y*2.6) for x,y in pts]))
        g=transform(stroke(stretched,thick,width=w),yy=1/2.6,width=w)
        return clean(g)
    raise KeyError('No Fraktur drawing for '+char)


def double_struck(char,italic=False):
    w,data=skeleton(char)
    outer=draw_skeleton(w,data,110)
    inner=draw_skeleton(w,data,29)
    g=boolean(outer,inner,'difference')
    if italic:g=transform(g,yx=0.19,width=w)
    return g
